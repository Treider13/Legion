// ============================================================================
// LEGION — reg_delta: выбор регистров для «быстрого» обновления ADF4351 в
// коридоре (fast-scan). Без Arduino — host-тестируемо (pio test -e native).
//
// Факт (даташит ADF4351 Rev. A, «Program Modes» + «Register Initialization»):
//  - при перестройке достаточно перезаписать ТОЛЬКО изменившиеся регистры;
//  - R0 всегда пишется ПОСЛЕДНИМ: его запись защёлкивает double-buffered поля
//    (MOD, phase, R-counter, CP и т.д.) и триггерит VCO band select;
//  - на большинстве шагов свипа меняются лишь R0 (INT/FRAC) и иногда R1 (MOD/
//    FRAC), R2–R5 постоянны → запись 1–2 регистров вместо 6.
//
// Приём подтверждён практикой: tctsui/ADF4351 (FastScanSetF обновляет один
// регистр вместо шести). ВАЖНО и честно: это срезает лишь время ЗАПИСИ по SPI
// (~40 мкс → ~7–13 мкс), но НЕ обходит физику захвата ФАПЧ (settling ~0.15–
// 0.5 мс) — предел скорости задаёт петля, а не контроллер. Аппаратный fast-lock
// (вывод SW + переделка loop-фильтра, даташит Fig. 31/32) здесь НЕ используется:
// на стоковых модулях SW не выведен (см. docs/analysis-upgrade.md).
// ============================================================================
#pragma once

#include <cstdint>

namespace legion {

// Формирует упорядоченный список индексов регистров для delta-записи:
//  - изменившиеся среди R5..R1 в порядке убывания (R5 первым);
//  - R0 ВСЕГДА последним (даже если не изменился) — защёлка + band select.
// out[] — буфер минимум на 6 элементов. Возвращает число записей (1..6).
inline int plan_delta_regs(const uint32_t prev[6], const uint32_t cur[6],
                           int out[6]) {
  int n = 0;
  for (int i = 5; i >= 1; --i) {
    if (prev[i] != cur[i]) {
      out[n++] = i;
    }
  }
  out[n++] = 0;  // R0 последним — всегда
  return n;
}

}  // namespace legion
