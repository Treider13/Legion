// ============================================================================
// LEGION — драйвер PE43702: 7-битный цифровой аттенюатор 9 кГц–4 ГГц,
// 0–31.75 дБ с шагом 0.25 дБ (факт: dd1us.de — практика с ADF4351-модулями).
// Serial-интерфейс: SI/CLK/LE, 8 бит MSB first, LE-импульс защёлкивает.
// Если модуль не подключён — запись уходит «в никуда», безвредно.
// ============================================================================
#pragma once

#include <Arduino.h>

namespace legion {

class Attenuator {
 public:
  void begin();
  // Установить затухание в дБ; квантование к 0.25 дБ, диапазон 0–31.75.
  // Возвращает фактически установленное значение.
  float setDb(float db);
  float getDb() const { return _db; }

 private:
  float _db = 0.0f;
};

}  // namespace legion
